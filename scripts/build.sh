#!/usr/bin/env bash
#
# Builds every installable zip from the current tree into dist/:
#   dist/com_muruguard-<component version>.zip
#   dist/plg_muruguardshield-<plugin version>.zip
#   dist/pkg_muruguard-<component version>.zip   (bundle of the two above)
#
# Also regenerates the vendored admin stylesheet
# (com_muruguard/media/css/muruguard.css) when the tailwindcss CLI is
# available; otherwise the committed CSS is kept as-is with a warning, so
# a missing toolchain can never silently ship unstyled output.
#
# Usage: scripts/build.sh [--skip-css]
#   --skip-css   don't touch the stylesheet even if tailwindcss exists.
#
# Env: DIST_DIR   output directory for the zips (default: dist). Point it
#   elsewhere (e.g. DIST_DIR=/tmp/muru-local) for local test builds so the
#   committed release zips are never overwritten.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

# Initialised up front so the EXIT traps below never hit `set -u` on an
# unset variable when a branch that creates them was skipped.
TW_TMP=""
PKG_TMP=""

SKIP_CSS=0
if [[ "${1:-}" == "--skip-css" ]]; then
  SKIP_CSS=1
fi

COM_MANIFEST="com_muruguard/muruguard.xml"
PLG_MANIFEST="plg_muruguardshield/muruguardshield.xml"
PKG_MANIFEST="pkg_muruguard/pkg_muruguard.xml"

manifest_version() {
  grep -oE '<version>[^<]+</version>' "$1" | sed -E 's#</?version>##g'
}

COM_VER="$(manifest_version "$COM_MANIFEST")"
PLG_VER="$(manifest_version "$PLG_MANIFEST")"
PKG_VER="$(manifest_version "$PKG_MANIFEST")"

if [[ "$PKG_VER" != "$COM_VER" ]]; then
  echo "Error: $PKG_MANIFEST is at $PKG_VER but $COM_MANIFEST is at $COM_VER." >&2
  echo "The package version tracks the component version -- run scripts/release.sh $COM_VER first." >&2
  exit 1
fi

# --- 1. Vendored admin stylesheet -------------------------------------------
if [[ "$SKIP_CSS" -eq 1 ]]; then
  echo "Skipping stylesheet rebuild (--skip-css)."
elif command -v tailwindcss >/dev/null 2>&1; then
  echo "Rebuilding media/css/muruguard.css with $(tailwindcss --help 2>/dev/null | head -n 1 || echo tailwindcss)..."
  TW_TMP="$(mktemp -d)"
  trap '[ -n "$TW_TMP" ] && rm -rf "$TW_TMP"' EXIT
  cat > "$TW_TMP/tailwind.config.js" <<EOF
// Generated by scripts/build.sh -- mirrors the scoping the admin page
// relies on: every utility under #muruguard-root, no global reset.
module.exports = {
  important: '#muruguard-root',
  corePlugins: { preflight: false },
  content: [
    '$REPO_ROOT/com_muruguard/admin/views/scanner/tmpl/*.php',
    '$REPO_ROOT/com_muruguard/admin/views/scanner/*.php',
    '$REPO_ROOT/com_muruguard/admin/helpers/*.php',
    '$REPO_ROOT/com_muruguard/admin/controllers/*.php',
    '$REPO_ROOT/com_muruguard/admin/models/*.php',
    '$REPO_ROOT/com_muruguard/admin/language/en-GB/*.ini',
    '$REPO_ROOT/plg_muruguardshield/*.php',
  ],
};
EOF
  printf '@tailwind base;\n@tailwind components;\n@tailwind utilities;\n' > "$TW_TMP/input.css"
  TW_VERSION="$(tailwindcss --help 2>/dev/null | head -n 1 | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' || echo unknown)"
  tailwindcss -c "$TW_TMP/tailwind.config.js" -i "$TW_TMP/input.css" -o "$TW_TMP/muruguard.css" --minify
  {
    printf '/*! MuRu Guard admin utilities | generated by Tailwind CSS v%s (see scripts/build.sh) | scoped to #muruguard-root, no preflight | DO NOT EDIT BY HAND */\n' "$TW_VERSION"
    cat "$TW_TMP/muruguard.css"
  } > com_muruguard/media/css/muruguard.css
  echo "Stylesheet rebuilt ($(wc -c < com_muruguard/media/css/muruguard.css) bytes)."
else
  echo "Warning: tailwindcss CLI not found -- keeping the committed media/css/muruguard.css as-is." >&2
  echo "If you changed admin markup classes, install tailwindcss (npm i -g tailwindcss@3) and re-run." >&2
fi

# --- 2. Static checks ---------------------------------------------------------
if [[ ! -f tests/static-checks.php ]]; then
  echo "Warning: tests/static-checks.php not found -- skipping static checks." >&2
elif command -v php >/dev/null 2>&1; then
  echo "Running static checks..."
  php tests/static-checks.php
else
  echo "Warning: php not found -- skipping static checks." >&2
fi

# --- 3. Build zips --------------------------------------------------------------
DIST_DIR="${DIST_DIR:-dist}"
case "$DIST_DIR" in
  /*) ;;
  *) DIST_DIR="$REPO_ROOT/$DIST_DIR" ;;
esac
mkdir -p "$DIST_DIR"

COM_ZIP="$DIST_DIR/com_muruguard-${COM_VER}.zip"
PLG_ZIP="$DIST_DIR/plg_muruguardshield-${PLG_VER}.zip"
PKG_ZIP="$DIST_DIR/pkg_muruguard-${COM_VER}.zip"

echo "Building $COM_ZIP ..."
rm -f "$COM_ZIP"
# The data/ dir is excluded wholesale and the SHIPPED files added back
# explicitly, so a scan-history/cache/log file from a local dev copy can
# never accidentally end up inside a distributed zip. (The .htaccess is an
# intentional, documented part of the package -- defence in depth for the
# data dir -- not runtime data.)
(cd com_muruguard && zip -qr "$COM_ZIP" . -x ".*" -x "admin/helpers/data/*")
(cd com_muruguard && zip -q "$COM_ZIP" admin/helpers/data/index.html admin/helpers/data/joomla_core_checksums.php admin/helpers/data/.htaccess)

echo "Building $PLG_ZIP ..."
rm -f "$PLG_ZIP"
(cd plg_muruguardshield && zip -qr "$PLG_ZIP" . -x ".*")

echo "Building $PKG_ZIP ..."
rm -f "$PKG_ZIP"
PKG_TMP="$(mktemp -d)"
trap '[ -n "$PKG_TMP" ] && rm -rf "$PKG_TMP"; [ -n "$TW_TMP" ] && rm -rf "$TW_TMP"' EXIT
cp "$PKG_MANIFEST" "$PKG_TMP/pkg_muruguard.xml"
cp "$COM_ZIP" "$PKG_TMP/com_muruguard.zip"
cp "$PLG_ZIP" "$PKG_TMP/plg_muruguardshield.zip"
# The bundle's own language files (the manifest's <languages folder="language">
# resolves against the package root, same as any other extension type).
cp -r pkg_muruguard/language "$PKG_TMP/language"
(cd "$PKG_TMP" && zip -qr "$PKG_ZIP" pkg_muruguard.xml com_muruguard.zip plg_muruguardshield.zip language -x "language/.DS_Store" "language/*/.DS_Store")

# --- 4. Verify layouts ------------------------------------------------------------
# NOTE: listings are captured into variables first, never piped straight
# into `grep -q`: grep -q exits on the first match, which SIGPIPEs unzip,
# and under `set -o pipefail` that dead writer fails the whole pipeline
# even when the pattern matched.
fail=0
com_listing="$(unzip -l "$COM_ZIP")"
plg_listing="$(unzip -l "$PLG_ZIP")"
pkg_listing="$(unzip -l "$PKG_ZIP")"
check_in_zip() {
  if ! grep -qE " $2"'$' <<<"$1"; then
    echo "Error: $2 is missing from $3 -- Joomla install would fail." >&2
    fail=1
  fi
}
check_in_zip "$com_listing" "muruguard.xml" "$COM_ZIP"
check_in_zip "$com_listing" "media/css/muruguard.css" "$COM_ZIP"
check_in_zip "$com_listing" "admin/helpers/data/.htaccess" "$COM_ZIP"
check_in_zip "$plg_listing" "muruguardshield.xml" "$PLG_ZIP"
check_in_zip "$pkg_listing" "pkg_muruguard.xml" "$PKG_ZIP"
check_in_zip "$pkg_listing" "com_muruguard.zip" "$PKG_ZIP"
check_in_zip "$pkg_listing" "plg_muruguardshield.zip" "$PKG_ZIP"
check_in_zip "$pkg_listing" "language/en-GB/en-GB.pkg_muruguard.sys.ini" "$PKG_ZIP"

# A runtime data file inside the component zip means the exclusion above broke.
if grep -qE "admin/helpers/data/(scan-history|scan-progress|geoip-cache|vulnfeed-cache|attack-log|login-attempts|ip-list|false-positives|protected-users-state)\.php" <<<"$com_listing"; then
  echo "Error: $COM_ZIP contains a runtime data file that must never ship." >&2
  fail=1
fi

# Junk that must never ship (macOS metadata, editor backups).
if grep -qE "\.DS_Store|\.bak$" <<<"$com_listing"$'\n'"$plg_listing"; then
  echo "Error: a zip contains junk files (.DS_Store / .bak)." >&2
  fail=1
fi

if [[ "$fail" -ne 0 ]]; then
  exit 1
fi

echo ""
echo "Built:"
echo "  $COM_ZIP"
echo "  $PLG_ZIP"
echo "  $PKG_ZIP"
